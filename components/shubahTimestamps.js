const DIACRITIC_REGEX = /[\u064B-\u065F\u0670\u06D6-\u06ED\u25C6\u0658\u0659]/g;

export function padSurahId(surahNumber) {
  if (!surahNumber && surahNumber !== 0) return null;
  const n = Number(surahNumber);
  if (!Number.isFinite(n) || n <= 0) return null;
  return String(n).padStart(3, "0");
}

export function getShubahAudioUrlForSurah(surahNumber) {
  const id = padSurahId(surahNumber);
  if (!id) return null;
  return `${SHUBAH_AUDIO_BASE_URL}/${id}.mp3`;
}

export function normalizeArabic(text) {
  if (!text) return "";
  return text.replace(DIACRITIC_REGEX, "").trim();
}

const normalizeForSearch = (text) =>
  normalizeArabic(text).replace(/[\s\u0640\.]/g, "");

// Simple position-aware similarity between two normalized strings (0–1)
const similarityScore = (a, b) => {
  if (!a || !b) return 0;
  const maxLen = Math.max(a.length, b.length);
  if (maxLen === 0) return 0;
  const minLen = Math.min(a.length, b.length);
  let matches = 0;
  for (let i = 0; i < minLen; i++) {
    if (a[i] === b[i]) matches += 1;
  }
  // Also reward shared characters out of position a bit
  const setA = new Set(a.split(""));
  const setB = new Set(b.split(""));
  let shared = 0;
  setA.forEach((ch) => {
    if (setB.has(ch)) shared += 1;
  });
  const charOverlap = shared / Math.max(setA.size, setB.size || 1);
  return (matches / maxLen) * 0.7 + charOverlap * 0.3;
};

export function getWordSegmentForText(surahNumber, rawWordText, options = {}) {
  const id = padSurahId(surahNumber);
  if (!id || !rawWordText) return null;
  const data = TIMESTAMP_MAP[id];
  if (!data) return null;

  let words = [];
  if (Array.isArray(data.word_segments)) {
    words = data.word_segments;
  } else if (Array.isArray(data.segments)) {
    words = data.segments.flatMap((seg) => seg.words || []);
  }

  if (!words.length) return null;

  const target = normalizeForSearch(rawWordText);
  if (!target) return null;

  // Exact / prefix match on normalized text
  let match =
    words.find((w) => normalizeForSearch(w.word) === target) ||
    // Fallback: startsWith or includes for robustness
    words.find((w) => normalizeForSearch(w.word).startsWith(target)) ||
    words.find((w) => target.startsWith(normalizeForSearch(w.word)));

  if (match) {
    return { ...match, source: "word" };
  }

  const contextSeq =
    Array.isArray(options.contextSequence) && options.contextSequence.length > 0
      ? options.contextSequence.map((t) => normalizeForSearch(t)).filter(Boolean)
      : null;

  // Fuzzy match: pick the closest word by similarity score, above a threshold
  let bestWord = null;
  let bestScore = 0;
  for (const w of words) {
    const norm = normalizeForSearch(w.word || "");
    if (!norm) continue;
    const score = similarityScore(target, norm);
    if (score > bestScore) {
      bestScore = score;
      bestWord = w;
    }
  }

  // Require a reasonably close match to avoid random jumps
  if (bestWord && bestScore >= 0.6 && !contextSeq) {
    return { ...bestWord, source: "fuzzy", similarity: bestScore };
  }

  // If we have line context, try to match a short phrase window
  if (contextSeq && contextSeq.length >= 2) {
    const normWords = words.map((w) => normalizeForSearch(w.word || ""));
    const winLen = contextSeq.length;
    let bestWindowScore = 0;
    let bestWindowCenterIndex = null;

    for (let i = 0; i <= normWords.length - winLen; i++) {
      let sum = 0;
      for (let j = 0; j < winLen; j++) {
        sum += similarityScore(contextSeq[j], normWords[i + j]);
      }
      const avg = sum / winLen;
      if (avg > bestWindowScore) {
        bestWindowScore = avg;
        bestWindowCenterIndex = i + Math.floor(winLen / 2);
      }
    }

    if (
      bestWindowCenterIndex !== null &&
      bestWindowScore >= 0.55 &&
      words[bestWindowCenterIndex]
    ) {
      return {
        ...words[bestWindowCenterIndex],
        source: "context-window",
        similarity: bestWindowScore,
      };
    }
  }

  // Fallback: try to find a larger segment (verse-like chunk) whose text contains this word
  if (Array.isArray(data.segments)) {
    const seg = data.segments.find((segment) => {
      if (!segment.text) return false;
      const segNorm = normalizeForSearch(segment.text);
      return segNorm.includes(target);
    });
    if (seg && typeof seg.start === "number" && typeof seg.end === "number") {
      return {
        word: rawWordText,
        start: seg.start,
        end: seg.end,
        score: null,
        source: "segment",
      };
    }
  }

  return null;
}

